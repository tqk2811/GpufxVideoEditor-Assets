def fail(message):
    sys.exit(f"error: {message}")


def display_name(slug):
    return slug.replace("_", " ").replace("-", " ").strip().title()


def flac_duration(path):
    """Duration in seconds from the STREAMINFO block (total samples / sample rate)."""
    with open(path, "rb") as f:
        head = f.read(10)
        if head[:3] == b"ID3":  # skip a leading ID3v2 tag
            size = ((head[6] & 0x7F) << 21) | ((head[7] & 0x7F) << 14) | ((head[8] & 0x7F) << 7) | (head[9] & 0x7F)
            f.seek(10 + size)
        else:
            f.seek(0)
        if f.read(4) != b"fLaC":
            fail(f"{path.name}: not a FLAC file")
        block = f.read(4)
        if len(block) < 4 or (block[0] & 0x7F) != 0:
            fail(f"{path.name}: STREAMINFO is not the first metadata block")
        info = f.read(34)
    if len(info) < 34:
        fail(f"{path.name}: truncated STREAMINFO")
    packed = int.from_bytes(info[10:18], "big")  # 20 bit rate, 3 channels, 5 bits depth, 36 bit samples
    sample_rate = packed >> 44
    total_samples = packed & ((1 << 36) - 1)
    if sample_rate == 0 or total_samples == 0:
        fail(f"{path.name}: STREAMINFO has no sample rate or length")
    return total_samples / sample_rate


def ffprobe_duration(path):
    exe = shutil.which("ffprobe")
    if not exe:
        return None
    result = subprocess.run(
        [exe, "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", str(path)],
        capture_output=True, text=True, check=False)
    try:
        return float(result.stdout.strip())
    except ValueError:
        return None


def load_catalog(path):
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        fail(f"{path}: catalog is not a list")
    return data


def round_duration(value):
    return round(float(value), 3)


def sfx_items(sfx_dir, stats):
    """Group the sfx catalog by category: {category: [(item, source file), ...]}."""
    catalog = load_catalog(sfx_dir / "catalog.json")
    groups = {}
    listed = set()
    for entry in catalog:
        name = entry["name"]
        category = entry["cat"]
        source = sfx_dir / f"{name}.flac"
        if not source.is_file():
            fail(f"sfx/{name}.flac listed in the catalog does not exist")
        listed.add(source.name)
        header = round_duration(flac_duration(source))
        stats["flac_vs_catalog_max_diff"] = max(stats.get("flac_vs_catalog_max_diff", 0.0), abs(header - float(entry["dur"])))
        item = {
            "id": name,
            "file": f"audio/{source.name}",
            "name": display_name(name),
            "duration": header,
            "tags": list(entry["tags"]) if entry.get("tags") else [category],
            "category": category,
            "loop": bool(entry["loop"]) if "loop" in entry else category in LOOP_CATEGORIES,
        }
        groups.setdefault(category, []).append((item, source))
    unlisted = sorted(p.name for p in sfx_dir.glob("*.flac") if p.name not in listed)
    if unlisted:
        fail(f"flac files missing from the sfx catalog: {', '.join(unlisted)}")
    return groups


def music_items(music_dir, stats):
    catalog = load_catalog(music_dir / "catalog.json")
    items = []
    listed = set()
    for entry in catalog:
        source = music_dir / entry["file"]
        if not source.is_file():
            fail(f"music/{entry['file']} listed in the catalog does not exist")
        listed.add(source.name)
        if entry.get("dur") is not None:
            duration = round_duration(entry["dur"])
            stats["mp3_catalog"] = stats.get("mp3_catalog", 0) + 1
        else:
            probed = ffprobe_duration(source)
            if probed is None:
                fail(f"music/{source.name}: no catalog duration and ffprobe is not available")
            duration = round_duration(probed)
            stats["mp3_ffprobe"] = stats.get("mp3_ffprobe", 0) + 1
        slug = entry["name"]
        mood = entry.get("mood")
        items.append(({
            "id": slug,
            "file": f"audio/{source.name}",
            "name": display_name(slug),
            "duration": duration,
            "tags": [mood] if mood else ["music"],
            "category": mood or "music",
            "loop": bool(entry["loop"]) if "loop" in entry else False,
        }, source))
    unlisted = sorted(p.name for p in music_dir.glob("*.mp3") if p.name not in listed)
    if unlisted:
        fail(f"mp3 files missing from the music catalog: {', '.join(unlisted)}")
    return items


def build_manifest(kind, pack_id, name, items):
    return {
        "format": 1,
        "type": kind,
        "id": pack_id,
        "name": name,
        "version": VERSION,
        "license": {"spdx": "MIT", "files": ["LICENSE.txt", "NOTICE.txt"]},
        "items": [item for item, _ in items],
    }


def validate(zip_name, manifest, items):
    seen = set()
    for item, source in items:
        if not ID_PATTERN.match(item["id"]):
            fail(f"{zip_name}: id '{item['id']}' does not match [a-z0-9._-]+")
        if item["id"] in seen:
            fail(f"{zip_name}: duplicate id '{item['id']}'")
        seen.add(item["id"])
        if not source.is_file():
            fail(f"{zip_name}: file {source} does not exist")
        if not item["duration"] > 0:
            fail(f"{zip_name}: item '{item['id']}' has no duration")
    if not ID_PATTERN.match(manifest["id"]):
        fail(f"{zip_name}: pack id '{manifest['id']}' does not match [a-z0-9._-]+")


def write_zip(target, manifest, items):
    text_files = [
        ("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"),
        ("LICENSE.txt", LICENSE_TEXT),
        ("NOTICE.txt", NOTICE_TEXT),
    ]
    temporary = target.with_suffix(".zip.tmp")
    with zipfile.ZipFile(temporary, "w") as archive:
        def add(entry_name, data, compress):
            info = zipfile.ZipInfo(entry_name, FIXED_TIME)
            info.create_system = 3
            info.external_attr = 0o644 << 16
            info.compress_type = compress
            archive.writestr(info, data, compresslevel=9 if compress == zipfile.ZIP_DEFLATED else None)

        for entry_name, text in text_files:
            add(entry_name, text.encode("utf-8"), zipfile.ZIP_DEFLATED)
        for item, source in sorted(items, key=lambda pair: pair[0]["file"]):
            add(item["file"], source.read_bytes(), zipfile.ZIP_STORED)
    temporary.replace(target)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, required=True, help="AI Video Studio assets directory (holds sfx/ and music/)")
    parser.add_argument("-o", "--output", type=Path, required=True, help="output directory")
    args = parser.parse_args()

    sfx_dir = args.source / "sfx"
    music_dir = args.source / "music"
    for needed in (sfx_dir / "catalog.json", music_dir / "catalog.json"):
        if not needed.is_file():
            fail(f"{needed} not found")

    stats = {}
    packs = []  # (zip name, manifest, items)
    for category, items in sorted(sfx_items(sfx_dir, stats).items()):
        items.sort(key=lambda pair: pair[0]["id"])
        manifest = build_manifest("sfx", f"avs-sfx-{category}", f"SFX: {category.capitalize()}", items)
        packs.append((f"sfx-{category}.zip", manifest, items))
    items = sorted(music_items(music_dir, stats), key=lambda pair: pair[0]["id"])
    packs.append(("music.zip", build_manifest("music", "avs-music", "Music", items), items))

    for zip_name, manifest, pack_items in packs:
        validate(zip_name, manifest, pack_items)

    args.output.mkdir(parents=True, exist_ok=True)
    total = 0
    for zip_name, manifest, pack_items in packs:
        target = args.output / zip_name
        write_zip(target, manifest, pack_items)
        total += len(pack_items)
        print(f"{zip_name}\t{len(pack_items)} items\t{target.stat().st_size} bytes")
    print(f"packed {len(packs)} zip(s), {total} audio item(s)")
    print(f"max |FLAC header - catalog dur| = {stats.get('flac_vs_catalog_max_diff', 0.0):.3f} s; "
          f"mp3 durations: {stats.get('mp3_catalog', 0)} from catalog, {stats.get('mp3_ffprobe', 0)} from ffprobe")


if __name__ == "__main__":
    main()
